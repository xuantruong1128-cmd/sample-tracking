/**
 * Fetches the expected next JOB Code (preview only, non-mutating)
 */
export async function fetchPreviewJobCode(targetDate?: string): Promise<string | null> {
  try {
    const { data, error } = await supabase.rpc('preview_next_job_code', {
      p_target_timestamp: targetDate || new Date().toISOString(),
    });
    if (error || !data) {
      return null;
    }
    return data as string;
  } catch {
    return null;
  }
}

/**
 * Fetches unique Workcenters with Descriptions from Supabase Workcenter Master table.
 * Falls back to verified master constants if remote query fails.
 */
export async function fetchWorkcenterMaster(): Promise<WorkcenterOption[]> {
  try {
    const { data, error } = await supabase
      .from('workcenter_master')
      .select('code, description')
      .eq('is_active', true)
      .order('code');

    if (error || !data || data.length === 0) {
      return UNIQUE_WORKCENTERS;
    }

    const seen = new Set<string>();
    const unique: WorkcenterOption[] = [];
    for (const item of data) {
      const codeUpper = item.code.trim().toUpperCase();
      let desc = item.description.trim();
      // R4 FIX 01 Safeguard: CYGG is always Cylindrical Grinding, never Auto Turn
      if (codeUpper === 'CYGG') {
        desc = 'Cylindrical Grinding';
      }
      if (!seen.has(codeUpper)) {
        seen.add(codeUpper);
        unique.push({ code: item.code.trim(), description: desc });
      }
    }
    return unique.length > 0 ? unique : UNIQUE_WORKCENTERS;
  } catch {
    return UNIQUE_WORKCENTERS;
  }
}

/**
 * Client-side validation for JOB creation form
 */
export function validateJobInput(input: CreateJobInput): { isValid: boolean; error?: string } {
  // UI-03 R3: In auto-generation mode, job_no is generated by database.
  // If explicitly provided as empty or whitespace, reject it.
  if (input.job_no !== undefined && input.job_no !== null && !input.job_no.trim()) {
    return { isValid: false, error: 'Vui lòng nhập Mã JOB (bắt buộc).' };
  }

  const partNo = input.part_no?.trim();
  if (!partNo) {
    return { isValid: false, error: 'Vui lòng nhập Mã chi tiết (Part Number bắt buộc).' };
  }

  if (typeof input.order_qty !== 'number' || isNaN(input.order_qty) || input.order_qty <= 0 || !Number.isInteger(input.order_qty)) {
    return { isValid: false, error: 'Số lượng yêu cầu (Quantity) phải là số nguyên dương lớn hơn 0.' };
  }

  const material = input.material?.trim();
  if (!material) {
    return { isValid: false, error: 'Vui lòng nhập Vật liệu (Material bắt buộc).' };
  }

  if (!input.planned_start_date) {
    return { isValid: false, error: 'Vui lòng chọn Ngày bắt đầu kế hoạch.' };
  }

  if (!input.planned_finish_date) {
    return { isValid: false, error: 'Vui lòng chọn Ngày hoàn thành kế hoạch.' };
  }

  if (input.planned_finish_date < input.planned_start_date) {
    return {
      isValid: false,
      error: `Ngày kết thúc (${input.planned_finish_date}) không được nhỏ hơn ngày bắt đầu (${input.planned_start_date}).`,
    };
  }

  if (!input.operations || input.operations.length === 0) {
    return { isValid: false, error: 'Quy trình gia công (Routing) phải có ít nhất 1 công đoạn.' };
  }

  for (let i = 0; i < input.operations.length; i++) {
    const op = input.operations[i];
    const wcOrName = (op.workcenter_code || op.operation_name || '').trim();
    if (!wcOrName) {
      return { isValid: false, error: `Tên công đoạn / Workcenter tại bước thứ ${i + 1} không được để trống.` };
    }
    if (typeof op.step_order !== 'number' || op.step_order < 1) {
      return { isValid: false, error: `Thứ tự công đoạn tại bước thứ ${i + 1} không hợp lệ.` };
    }

    // R4 FIX 02: Auto Turn CT Target check
    const isAutoTurn = isAutoTurnOperation(op);
    const rawCycle = op.planned_cycle_time_seconds ?? op.cycle_time;
    const num = rawCycle !== undefined && rawCycle !== null && rawCycle !== ('' as any) ? Number(rawCycle) : null;

    if (isAutoTurn && (num === null || isNaN(num) || num <= 0)) {
      return {
        isValid: false,
        error: `Công đoạn Auto Turn tại bước thứ ${i + 1} (OP${op.step_order || (i + 1) * 10}) bắt buộc phải nhập Thời gian chu kỳ mục tiêu (Cycle Time Target > 0).`,
      };
    }

    if (num !== null && (isNaN(num) || num <= 0)) {
      return { isValid: false, error: `Thời gian chu kỳ (Cycle Time Target) tại bước thứ ${i + 1} phải là số dương lớn hơn 0.` };
    }
  }

  // Check unique step orders
  const stepOrders = input.operations.map((o) => o.step_order);
  const uniqueSteps = new Set(stepOrders);
  if (uniqueSteps.size !== stepOrders.length) {
    return { isValid: false, error: 'Thứ tự các công đoạn (STT) không được trùng nhau.' };
  }

  return { isValid: true };
}

/**
 * Translates PostgreSQL error codes and messages into user-friendly Vietnamese messages
 */
export function translateJobCreationError(error: any): string {
  if (!error) return 'Đã xảy ra lỗi không xác định.';
  const msg = (error.message || String(error)).toLowerCase();

  // Duplicate key constraint
  if (msg.includes('duplicate key') || msg.includes('jobs_job_no_key') || msg.includes('đã tồn tại')) {
    return 'Mã JOB này đã tồn tại trong hệ thống. Vui lòng chọn một mã JOB khác.';
  }

  // Permission / Authorization
  if (msg.includes('quyền hạn bị từ chối') || msg.includes('only planning or admin') || msg.includes('permission denied')) {
    return 'Quyền hạn bị từ chối: Chỉ tài khoản thuộc bộ phận Planning hoặc Admin mới được phép tạo JOB.';
  }

  // Account state
  if (msg.includes('tài khoản chưa được kích hoạt') || msg.includes('is_user_active')) {
    return 'Tài khoản của bạn đã bị vô hiệu hóa hoặc chưa kích hoạt. Vui lòng liên hệ Admin.';
  }
  if (msg.includes('đổi mật khẩu') || msg.includes('has_completed_password_change')) {
    return 'Bạn cần hoàn tất đổi mật khẩu lần đầu trước khi có thể tạo JOB.';
  }

  // Check constraints
  if (msg.includes('chk_planned_dates') || msg.includes('ngày hoàn thành')) {
    return 'Ngày kết thúc kế hoạch phải sau hoặc cùng ngày bắt đầu.';
  }

  if (msg.includes('order_qty') || msg.includes('số nguyên dương')) {
    return 'Số lượng yêu cầu (Quantity) phải là số nguyên dương lớn hơn 0.';
  }

  if (msg.includes('cycle time') || msg.includes('thời gian chu kỳ')) {
    return error.message || 'Thời gian chu kỳ (Cycle Time Target) phải là số dương lớn hơn 0.';
  }

  if (msg.includes('routing') || msg.includes('công đoạn') || msg.includes('workcenter')) {
    return error.message || 'Dữ liệu công đoạn (Routing) không hợp lệ.';
  }

  if (msg.includes('network') || msg.includes('failed to fetch')) {
    return 'Không thể kết nối đến máy chủ cơ sở dữ liệu. Vui lòng kiểm tra đường truyền mạng.';
  }

  return error.message || 'Không thể tạo JOB mới. Vui lòng thử lại sau.';
}

/**
 * Creates a new JOB along with its ordered routing operations.
 * Executes atomically via Supabase PostgreSQL function `create_job_with_routing`.
 * If any error occurs, rolls back completely without leaving partial data.
 */
export async function createJobWithRouting(input: CreateJobInput): Promise<CreateJobResult> {
  // 1. Client-side validation
  const validation = validateJobInput(input);
  if (!validation.isValid) {
    throw new Error(validation.error || 'Dữ liệu không hợp lệ.');
  }

  // 2. Prepare normalized payload
  const trimmedJobNo = (input.job_no || '').trim();
  const trimmedPartNo = input.part_no.trim();
  const trimmedPartName = input.part_name?.trim() || trimmedPartNo;
  const trimmedCustomer = input.customer?.trim() || '';
  const trimmedMaterial = input.material.trim();
  const trimmedMaterialSpec = input.material_spec?.trim() || '';

  const normalizedOperations = input.operations.map((op, index) => {
    const stepOrder = op.step_order || (index + 1) * 10;
    const wcCode = (op.workcenter_code || op.operation_name || '').trim();
    const desc = (op.description || getWorkcenterDescription(wcCode) || op.operation_name || wcCode).trim();
    
    let cycleTime: number | null = null;
    const rawCycle = op.planned_cycle_time_seconds ?? op.cycle_time;
    if (rawCycle !== undefined && rawCycle !== null && rawCycle !== ('' as any)) {
      const num = Number(rawCycle);
      if (!isNaN(num) && num > 0) {
        cycleTime = num;
      }
    }

    const machineNo = (op.machine_no || op.planned_machine || '').trim() || null;
    const remark = (op.remark || '').trim() || null;

    return {
      step_order: stepOrder,
      workcenter_code: wcCode,
      description: desc,
      operation_name: desc,
      planned_cycle_time_seconds: cycleTime,
      machine_no: machineNo,
      planned_machine: machineNo,
      remark: remark,
    };
  });

  try {
    // Primary: Call atomic PostgreSQL stored function
    const { data: rpcData, error: rpcError } = await supabase.rpc('create_job_with_routing', {
      p_job_no: trimmedJobNo,
      p_part_no: trimmedPartNo,
      p_part_name: trimmedPartName,
      p_customer: trimmedCustomer,
      p_order_qty: input.order_qty,
      p_material: trimmedMaterial,
      p_material_spec: trimmedMaterialSpec,
      p_planned_start_date: input.planned_start_date,
      p_planned_finish_date: input.planned_finish_date,
      p_operations: normalizedOperations,
    });

    if (rpcError) {
      // If function doesn't exist (e.g. offline dev), fall back to direct insert
      if (rpcError.message?.includes('function') && rpcError.message?.includes('does not exist')) {
        return await createJobWithRoutingDirectFallback(input, normalizedOperations);
      }
      throw new Error(translateJobCreationError(rpcError));
    }

    const createdJob = rpcData as any;
    const createdJobId = createdJob?.id || createdJob?.job_id;
    const officialJobNo = createdJob?.job_no || trimmedJobNo;
    if (!createdJobId) {
      throw new Error('Máy chủ không trả về định danh của JOB mới tạo.');
    }

    // Query full job with operations to return to client
    const { data: fullJob, error: queryError } = await supabase
      .from('jobs')
      .select(`
        *,
        operations:job_operations(*)
      `)
      .eq('id', createdJobId)
      .single();

    if (queryError || !fullJob) {
      // Even if fetch failed, RPC succeeded
      return {
        success: true,
        job: {
          id: createdJobId,
          job_no: officialJobNo,
          part_no: trimmedPartNo,
          part_name: trimmedPartName,
          customer: trimmedCustomer,
          order_qty: input.order_qty,
          material: trimmedMaterial,
          material_spec: trimmedMaterialSpec,
          planned_start_date: input.planned_start_date,
          planned_finish_date: input.planned_finish_date,
          status: 'ACTIVE',
          created_at: new Date().toISOString(),
          updated_at: new Date().toISOString(),
          operations: normalizedOperations.map((op, idx) => ({
            id: `temp-${idx}`,
            job_id: createdJobId,
            step_order: op.step_order,
            workcenter_code: op.workcenter_code,
            description: op.description,
            operation_name: op.operation_name,
            planned_machine: op.machine_no,
            machine_no: op.machine_no,
            planned_cycle_time_seconds: op.planned_cycle_time_seconds,
            remark: op.remark,
            status: 'NOT_STARTED',
            created_at: new Date().toISOString(),
            updated_at: new Date().toISOString(),
          })) as JobOperation[],
        } as Job,
      };
    }

    return {
      success: true,
      job: fullJob as Job,
    };
  } catch (err: any) {
    throw new Error(translateJobCreationError(err));
  }
}

/**
 * Fallback direct insert with automated cleanup to ensure atomicity
 */
async function createJobWithRoutingDirectFallback(
  input: CreateJobInput,
  normalizedOperations: any[]
): Promise<CreateJobResult> {
  const finalJobNo = input.job_no?.trim() || (await fetchPreviewJobCode()) || `${new Date().toISOString().slice(0, 7).replace('-', '')}-001`;
  const trimmedJobNo = finalJobNo;
  const trimmedPartNo = input.part_no.trim();
  const trimmedPartName = input.part_name?.trim() || trimmedPartNo;
  const trimmedCustomer = input.customer?.trim() || '';
  const trimmedMaterial = input.material.trim();
  const trimmedMaterialSpec = input.material_spec?.trim() || '';

  // 1. Insert Job
  const { data: jobData, error: jobError } = await supabase
    .from('jobs')
    .insert({
      job_no: trimmedJobNo,
      part_no: trimmedPartNo,
      part_name: trimmedPartName,
      customer: trimmedCustomer,
      order_qty: input.order_qty,
      material: trimmedMaterial,
      material_spec: trimmedMaterialSpec || null,
      planned_start_date: input.planned_start_date,
      planned_finish_date: input.planned_finish_date,
      status: 'ACTIVE',
    })
    .select()
    .single();

  if (jobError || !jobData) {
    throw new Error(translateJobCreationError(jobError));
  }

  const newJobId = jobData.id;

  // 2. Insert Operations
  const opsToInsert = normalizedOperations.map((op) => ({
    job_id: newJobId,
    step_order: op.step_order,
    operation_name: op.operation_name,
    workcenter_code: op.workcenter_code,
    description: op.description,
    planned_machine: op.machine_no,
    machine_no: op.machine_no,
    planned_cycle_time_seconds: op.planned_cycle_time_seconds,
    remark: op.remark,
    status: 'NOT_STARTED',
  }));

  const { data: opsData, error: opsError } = await supabase
    .from('job_operations')
    .insert(opsToInsert)
    .select();

  if (opsError) {
    // ATOMIC CLEANUP: Rollback job creation to prevent partial data
    await supabase.from('jobs').delete().eq('id', newJobId);
    throw new Error(`Lỗi khi tạo quy trình công đoạn: ${translateJobCreationError(opsError)} (Đã hủy lưu JOB)`);
  }

  return {
    success: true,
    job: {
      ...jobData,
      operations: opsData as JobOperation[],
    } as Job,
  };
}

